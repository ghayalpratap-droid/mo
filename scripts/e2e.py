"""Browser CRUD verification. pip install playwright; playwright install chromium."""
import os
from playwright.sync_api import sync_playwright, expect
url=os.environ.get('FRONTEND_URL','http://localhost:5173')
with sync_playwright() as p:
    options={'headless':True}
    if os.environ.get('CHROMIUM_PATH'): options['executable_path']=os.environ['CHROMIUM_PATH']
    browser=p.chromium.launch(**options)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    page.goto(url)
    expect(page.get_by_role('heading',name='Employee directory.')).to_be_visible()
    page.get_by_role('button',name='Add employee').click()
    page.get_by_role('button',name='Create employee').click()
    expect(page.get_by_text('This field is required')).to_have_count(3)
    page.get_by_label('First name',exact=True).fill('Rahul')
    page.get_by_label('Last name',exact=True).fill('Sharma')
    page.get_by_label('Age',exact=True).fill('28')
    page.get_by_label('Address',exact=True).fill('Pune, Maharashtra')
    page.get_by_role('button',name='Create employee').click()
    expect(page.get_by_text('Employee created successfully.')).to_be_visible()
    row=page.get_by_role('row').filter(has=page.get_by_role('button',name='Rahul Sharma Employee'))
    expect(row).to_have_count(1)
    page.reload()
    expect(row).to_have_count(1)
    row.get_by_role('button',name='Rahul Sharma Employee').click()
    expect(page.get_by_role('heading',name='Employee details')).to_be_visible()
    page.get_by_role('button',name='Close dialog').click()
    row.get_by_role('button',name='Edit Rahul Sharma').click()
    page.get_by_label('Age',exact=True).fill('29')
    page.get_by_role('button',name='Save changes').click()
    expect(row.get_by_role('cell',name='29',exact=True)).to_be_visible()
    page.screenshot(path='/tmp/employee-desktop.png',full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    expect(page.get_by_role('button',name='Add employee')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile layout overflows'
    page.screenshot(path='/tmp/employee-mobile.png',full_page=True)
    row.get_by_role('button',name='Delete Rahul Sharma').click()
    page.get_by_role('button',name='Keep employee').click()
    expect(row).to_have_count(1)
    row.get_by_role('button',name='Delete Rahul Sharma').click()
    page.get_by_role('button',name='Delete employee',exact=True).click()
    expect(page.get_by_text('Employee deleted successfully.')).to_be_visible()
    expect(row).to_have_count(0)
    page.reload()
    expect(page.get_by_text('No employees found')).to_be_visible()
    browser.close()
print('PASS: Browser required-field validation, create, detail, refresh persistence, edit, cancel delete, delete and mobile layout')
